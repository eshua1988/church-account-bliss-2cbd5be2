-- A continuing decision does not create a new PDF accounting document.  Each
-- occurrence increases the amount of the original archived PDF transaction.
CREATE TABLE IF NOT EXISTS public.recurring_pdf_payment_occurrences (
  reminder_id uuid NOT NULL REFERENCES public.reminders(id) ON DELETE CASCADE,
  scheduled_for date NOT NULL,
  amount numeric NOT NULL CHECK (amount > 0),
  currency text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (reminder_id, scheduled_for)
);

-- Store the exact accounting row behind every existing PDF reminder.  Old
-- cards only stored the Storage path, so choose the original archive row, not
-- an occurrence generated by the old scheduler.
WITH source_rows AS (
  SELECT DISTINCT ON (reminder.id)
    reminder.id AS reminder_id,
    entry.id AS source_entry_id
  FROM public.reminders AS reminder
  JOIN public.pdf_archive_entries AS entry
    ON entry.user_id = reminder.user_id
   AND entry.source_reminder_id IS NULL
   AND entry.source_pdf_path = reminder.recurring_pdf->>'source_pdf_path'
  WHERE reminder.recurring_pdf IS NOT NULL
    AND NULLIF(reminder.recurring_pdf->>'source_entry_id', '') IS NULL
  ORDER BY reminder.id, entry.document_date ASC, entry.created_at ASC
)
UPDATE public.reminders AS reminder
SET recurring_pdf = reminder.recurring_pdf || jsonb_build_object('source_entry_id', source_rows.source_entry_id)
FROM source_rows
WHERE reminder.id = source_rows.reminder_id;

-- Preserve old generated occurrences as a ledger, merge their amount into the
-- source transaction, then remove the now redundant accounting rows.
WITH generated AS (
  SELECT entry.id, entry.source_reminder_id AS reminder_id, entry.scheduled_for,
         entry.amount, entry.currency
  FROM public.pdf_archive_entries AS entry
  WHERE entry.source_reminder_id IS NOT NULL
    AND entry.scheduled_for IS NOT NULL
), inserted AS (
  INSERT INTO public.recurring_pdf_payment_occurrences (reminder_id, scheduled_for, amount, currency)
  SELECT reminder_id, scheduled_for, amount, currency FROM generated
  ON CONFLICT (reminder_id, scheduled_for) DO NOTHING
  RETURNING reminder_id, scheduled_for, amount, currency
), totals AS (
  SELECT inserted.reminder_id, SUM(inserted.amount) AS amount, inserted.currency
  FROM inserted
  GROUP BY inserted.reminder_id, inserted.currency
)
UPDATE public.pdf_archive_entries AS source
SET amount = source.amount + totals.amount
FROM totals
JOIN public.reminders AS reminder ON reminder.id = totals.reminder_id
WHERE source.id = NULLIF(reminder.recurring_pdf->>'source_entry_id', '')::uuid
  AND source.currency = totals.currency;

DELETE FROM public.pdf_archive_entries
WHERE source_reminder_id IS NOT NULL
  AND scheduled_for IS NOT NULL
  AND EXISTS (
    SELECT 1 FROM public.recurring_pdf_payment_occurrences AS occurrence
    WHERE occurrence.reminder_id = pdf_archive_entries.source_reminder_id
      AND occurrence.scheduled_for = pdf_archive_entries.scheduled_for
  );

CREATE OR REPLACE FUNCTION public.process_due_reminders()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  item public.reminders%ROWTYPE;
  next_at timestamptz;
  scheduled_at timestamptz;
  scheduled_for_date date;
  source_entry_id uuid;
  payment_rows integer;
  processed integer := 0;
BEGIN
  FOR item IN
    SELECT * FROM public.reminders
    WHERE closed_at IS NULL
      AND next_notification_at IS NOT NULL
      AND next_notification_at <= now()
    ORDER BY next_notification_at
    FOR UPDATE SKIP LOCKED
  LOOP
    INSERT INTO public.notifications (user_id, title, message, type, is_read, metadata)
    VALUES (
      item.user_id,
      'Напоминание: ' || item.full_name,
      item.message,
      'reminder_alert',
      false,
      jsonb_build_object('reminder_id', item.id, 'contact', item.contact, 'scheduled_for', item.next_notification_at)
    );

    scheduled_at := item.next_notification_at;
    WHILE scheduled_at <= now() LOOP
      IF item.recurring_pdf IS NOT NULL THEN
        scheduled_for_date := (scheduled_at AT TIME ZONE 'Europe/Warsaw')::date;
        source_entry_id := NULLIF(item.recurring_pdf->>'source_entry_id', '')::uuid;
        IF source_entry_id IS NULL THEN
          RAISE EXCEPTION 'Для PDF-напоминания % не найдена исходная транзакция', item.id;
        END IF;

        INSERT INTO public.recurring_pdf_payment_occurrences (reminder_id, scheduled_for, amount, currency)
        VALUES (
          item.id,
          scheduled_for_date,
          (item.recurring_pdf->>'amount')::numeric,
          COALESCE(NULLIF(item.recurring_pdf->>'currency', ''), 'PLN')
        ) ON CONFLICT (reminder_id, scheduled_for) DO NOTHING;
        GET DIAGNOSTICS payment_rows = ROW_COUNT;

        IF payment_rows > 0 THEN
          UPDATE public.pdf_archive_entries
          SET amount = amount + (item.recurring_pdf->>'amount')::numeric
          WHERE id = source_entry_id
            AND user_id = item.user_id
            AND currency = COALESCE(NULLIF(item.recurring_pdf->>'currency', ''), 'PLN');
          IF NOT FOUND THEN
            RAISE EXCEPTION 'Исходная PDF-транзакция не найдена или имеет другую валюту';
          END IF;
        END IF;
      END IF;

      next_at := CASE item.repeat
        WHEN 'once' THEN NULL
        WHEN 'weekly' THEN scheduled_at + interval '1 week'
        WHEN 'monthly' THEN scheduled_at + interval '1 month'
        WHEN 'yearly' THEN scheduled_at + interval '1 year'
        ELSE NULL
      END;
      EXIT WHEN next_at IS NULL;
      scheduled_at := next_at;
    END LOOP;

    UPDATE public.reminders
    SET last_notified_at = now(), next_notification_at = next_at
    WHERE id = item.id;
    processed := processed + 1;
  END LOOP;
  RETURN processed;
END;
$$;
